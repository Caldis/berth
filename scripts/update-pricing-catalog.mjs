import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'

const LITELLM_URL =
  'https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json'
const MODELS_DEV_URL = 'https://models.dev/api.json'
const OUT_PATH = resolve('src/main/engine/pricing/catalog.generated.ts')

const generatedAt = new Date().toISOString()
const [litellm, modelsDev] = await Promise.all([
  fetchJson(LITELLM_URL),
  fetchJson(MODELS_DEV_URL)
])

const models = mergeCatalogs([
  ...convertModelsDevCatalog(modelsDev.json, { sourceUrl: MODELS_DEV_URL, updatedAt: generatedAt }),
  ...convertLiteLlmPricingCatalog(litellm.json, { sourceUrl: LITELLM_URL, updatedAt: generatedAt })
])

const snapshot = {
  version: 1,
  generatedAt,
  sources: [
    { name: 'litellm', url: LITELLM_URL, fetchedAt: litellm.fetchedAt },
    { name: 'models.dev', url: MODELS_DEV_URL, fetchedAt: modelsDev.fetchedAt }
  ],
  models
}

const content = `import type { PricingCatalogSnapshot } from './types'

// Generated by scripts/update-pricing-catalog.mjs. Do not edit by hand.
const snapshotJson = ${JSON.stringify(JSON.stringify(snapshot))}

export const PRICING_CATALOG_SNAPSHOT = JSON.parse(snapshotJson) as PricingCatalogSnapshot
`

await mkdir(dirname(OUT_PATH), { recursive: true })
await writeFile(OUT_PATH, content)
console.log(`Wrote ${models.length} pricing records to ${OUT_PATH}`)

async function fetchJson(url) {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`Failed to fetch ${url}: ${response.status}`)
  return {
    fetchedAt: new Date().toISOString(),
    json: await response.json()
  }
}

function convertLiteLlmPricingCatalog(raw, options) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return []

  return Object.entries(raw).flatMap(([modelId, record]) => {
    if (modelId === 'sample_spec' || !record || typeof record !== 'object') return []

    const inputCostPerToken = finiteNumber(record.input_cost_per_token)
    const outputCostPerToken = finiteNumber(record.output_cost_per_token)
    if (inputCostPerToken == null || outputCostPerToken == null) return []

    const provider = stringValue(record.litellm_provider) ?? inferProvider(modelId)
    const model = stripProviderPrefix(modelId, provider)

    return [
      pruneUndefined({
        id: provider ? `${provider}/${model}` : model,
        model,
        provider,
        aliases: builtInAliases(provider, model),
        inputCostPerToken,
        outputCostPerToken,
        cacheReadInputCostPerToken: finiteNumber(record.cache_read_input_token_cost),
        cacheCreationInputCostPerToken: finiteNumber(record.cache_creation_input_token_cost),
        reasoningOutputCostPerToken: finiteNumber(record.output_cost_per_reasoning_token),
        contextWindow: finiteNumber(record.max_input_tokens) ?? finiteNumber(record.max_tokens),
        maxOutputTokens: finiteNumber(record.max_output_tokens) ?? finiteNumber(record.max_tokens),
        source: 'litellm',
        sourceUrl: options.sourceUrl,
        updatedAt: options.updatedAt
      })
    ]
  })
}

function convertModelsDevCatalog(raw, options) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return []

  const records = []
  for (const [provider, providerRecord] of Object.entries(raw)) {
    const models = providerRecord?.models
    if (!models || typeof models !== 'object' || Array.isArray(models)) continue

    for (const [modelId, modelRecord] of Object.entries(models)) {
      const cost = modelRecord?.cost
      if (!modelRecord || !cost || typeof cost !== 'object') continue

      const inputCostPerToken = millionTokenCost(cost.input)
      const outputCostPerToken = millionTokenCost(cost.output)
      if (inputCostPerToken == null || outputCostPerToken == null) continue

      const limit = modelRecord.limit && typeof modelRecord.limit === 'object' ? modelRecord.limit : {}
      const model = stringValue(modelRecord.id) ?? modelId.toLowerCase()

      records.push(
        pruneUndefined({
          id: `${provider}/${model}`,
          model,
          provider,
          inputCostPerToken,
          outputCostPerToken,
          cacheReadInputCostPerToken: millionTokenCost(cost.cache_read),
          cacheCreationInputCostPerToken: millionTokenCost(cost.cache_write),
          reasoningOutputCostPerToken: millionTokenCost(cost.reasoning),
          contextWindow: finiteNumber(limit.context),
          maxOutputTokens: finiteNumber(limit.output),
          source: 'models.dev',
          sourceUrl: options.sourceUrl,
          updatedAt: options.updatedAt ?? stringValue(modelRecord.last_updated)
        })
      )
    }
  }

  return records
}

function mergeCatalogs(records) {
  const byId = new Map()
  for (const record of records) byId.set(record.id ?? record.model, record)
  return Array.from(byId.values()).sort((left, right) =>
    (left.id ?? left.model).localeCompare(right.id ?? right.model)
  )
}

function builtInAliases(provider, model) {
  if (provider === 'anthropic' && model === 'claude-sonnet-4-20250514') return ['claude-sonnet-4']
  return undefined
}

function millionTokenCost(value) {
  const cost = finiteNumber(value)
  return cost == null ? undefined : cost / 1_000_000
}

function finiteNumber(value) {
  if (typeof value === 'number' && Number.isFinite(value)) return value
  if (typeof value === 'string' && value.trim()) {
    const parsed = Number(value)
    if (Number.isFinite(parsed)) return parsed
  }
  return undefined
}

function stringValue(value) {
  return typeof value === 'string' && value.trim() ? value.trim().toLowerCase() : undefined
}

function inferProvider(modelId) {
  const id = modelId?.trim().toLowerCase()
  if (!id) return undefined
  const slashIndex = id.indexOf('/')
  if (slashIndex > 0) return id.slice(0, slashIndex)
  const dotIndex = id.indexOf('.')
  if (dotIndex > 0) return id.slice(0, dotIndex)
  return undefined
}

function stripProviderPrefix(modelId, provider) {
  const normalized = modelId.trim().toLowerCase()
  if (provider && normalized.startsWith(`${provider}/`)) return normalized.slice(provider.length + 1)
  return normalized
}

function pruneUndefined(value) {
  for (const key of Object.keys(value)) {
    if (value[key] === undefined) delete value[key]
  }
  return value
}
